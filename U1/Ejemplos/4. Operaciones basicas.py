# **Manejo del tipo de datos numéricos en Python**
## **Sumatoria**
print("La suma es: ",12 + 67)
## **Resta**
print("La resta es: ",89 - 4)
## **Multiplicación**
print("La multiplicacion es: ",9 * 7)
## **División**
print("La division es: ",35 / 5)
## **Residuo de la división**
print("El residuo es: ", 40 % 5)
print("El residuo es: ", 40 % 6)
## **División entera**
print("La division entera es: ", 40 // 7)
## **Cuadrado de un numero o potencia**
print("La potencia es: ", 5 ** 2)  # Elevar al cuadrado un numero
print("La potencia es: ", 5 ** 9)  # Se eleva el 5 a la potencia de 9
## **Operaciones respetando el nivel de precedencia de operadores**
print("Nivel de precedencia: ", 3 - 2 + 4 * 10)  # El orden de precedencia es primero multiplicación y luego suma
